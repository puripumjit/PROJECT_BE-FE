-- ---------- ชนิดข้อมูล (enum) ----------
CREATE TYPE user_role AS ENUM ('admin', 'member');

-- ---------- ฟังก์ชันอัปเดต updated_at อัตโนมัติ ----------
CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- =====================================================================
-- 1) users : ผู้ใช้งาน (role = admin | member)
-- =====================================================================
CREATE TABLE users (
  id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  username       VARCHAR(50)  NOT NULL UNIQUE,
  email          VARCHAR(255) NOT NULL,
  password_hash  TEXT         NOT NULL,              -- เก็บ hash (bcrypt/argon2) ห้ามเก็บรหัสผ่านจริง
  display_name   VARCHAR(100),
  avatar_url     TEXT,
  role           user_role    NOT NULL DEFAULT 'member',
  is_active      BOOLEAN      NOT NULL DEFAULT TRUE,
  last_login_at  TIMESTAMPTZ,
  created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_lower_uq ON users (lower(email));   -- อีเมลซ้ำไม่ได้ ไม่สนตัวพิมพ์เล็ก/ใหญ่
CREATE TRIGGER users_updated_at BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- =====================================================================
-- 2) categories : หมวดหมู่บอร์ดเกม (10 หมวดในดีไซน์)
-- =====================================================================
CREATE TABLE categories (
  id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  slug        VARCHAR(50)  NOT NULL UNIQUE,          -- ใช้ใน URL เช่น /games?category=family
  name_th     VARCHAR(150) NOT NULL,
  name_en     VARCHAR(150) NOT NULL,
  description TEXT,
  icon        VARCHAR(20),                           -- อีโมจิหรือชื่อไอคอน
  cover_url   TEXT,
  sort_order  INT          NOT NULL DEFAULT 0,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE TRIGGER categories_updated_at BEFORE UPDATE ON categories
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- =====================================================================
-- 3) games : ข้อมูลบอร์ดเกมทั้งหมดอยู่ในตารางเดียว
--    (วิธีเล่น / จุดเด่น / แท็ก เก็บเป็น array ในตัวเกม)
-- =====================================================================
CREATE TABLE games (
  id              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  slug            VARCHAR(150) NOT NULL UNIQUE,      -- เช่น catan -> /games/catan
  name            VARCHAR(200) NOT NULL,
  category_id     BIGINT       NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
  description     TEXT,
  publisher       VARCHAR(150),                      -- ผู้ผลิต
  designer        VARCHAR(150),
  game_type       VARCHAR(100),                      -- เช่น Strategy
  min_players     SMALLINT     NOT NULL,
  max_players     SMALLINT     NOT NULL,
  min_play_time   SMALLINT     NOT NULL,             -- นาที
  max_play_time   SMALLINT     NOT NULL,
  min_age         SMALLINT     NOT NULL DEFAULT 0,
  how_to_play     TEXT[]       NOT NULL DEFAULT '{}',  -- วิธีเล่น (ย่อ) ลำดับใน array = ลำดับข้อ
  highlights      TEXT[]       NOT NULL DEFAULT '{}',  -- จุดเด่น
  tags            TEXT[]       NOT NULL DEFAULT '{}',  -- แท็ก เช่น {ครอบครัว,วางพื้นที่}
  is_published    BOOLEAN      NOT NULL DEFAULT TRUE,  -- ซ่อน/แสดงบนหน้าเว็บ
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT games_players_chk CHECK (min_players >= 1 AND min_players <= max_players),
  CONSTRAINT games_time_chk    CHECK (min_play_time >= 1 AND min_play_time <= max_play_time),
  CONSTRAINT games_age_chk     CHECK (min_age >= 0)
);
CREATE INDEX games_category_idx   ON games (category_id);
CREATE INDEX games_published_idx  ON games (is_published);
CREATE INDEX games_name_lower_idx ON games (lower(name));
CREATE INDEX games_tags_gin_idx   ON games USING GIN (tags);   -- ค้นหา: WHERE tags @> ARRAY['ครอบครัว']
CREATE TRIGGER games_updated_at BEFORE UPDATE ON games
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- =====================================================================
-- 4) user_favorites : "รายการโปรด" (ปุ่มหัวใจ)
-- =====================================================================
CREATE TABLE user_favorites (
  user_id   BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  game_id   BIGINT      NOT NULL REFERENCES games(id) ON DELETE CASCADE,
  added_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, game_id)
);
CREATE INDEX user_favorites_game_idx ON user_favorites (game_id);

